const CODEX_HOME = process.env.CODEX_HOME || path.join(os.homedir(), ".codex");
export const CODEX_CONFIG_FILE = path.join(CODEX_HOME, "config.toml");

export function getNativeProfilePath(name: string): string {
  return path.join(CODEX_HOME, `${name}.config.toml`);
}

export function escapeTomlString(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function toTomlArray(values: string[]): string {
  const escaped = values.map((v) => `"${escapeTomlString(v)}"`);
  return `[${escaped.join(", ")}]`;
}

